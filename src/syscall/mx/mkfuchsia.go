func (p *parser) parse() (syscalls []magentaSyscallDef, err error) {
	if len(p.buf) == 0 {
		return syscalls, nil
	}

	p.nextRune()
	for {
		t, lit := p.nextToken()
		if lit == "syscall" {
			call, err := p.parseSyscall()
			if err != nil {
				return nil, err
			}
			if strings.Contains(call.name, "_test") {
				continue
			}
			syscalls = append(syscalls, call)
			continue
		}
		if t == tokenEOF {
			return syscalls, nil
		}
		if t == tokenBad {
			return nil, p.errorf("bad token: %s", lit)
		}
		return nil, p.errorf("unexpected token: %q (literal %q)", t, lit)
	}
}

func (p *parser) expect(want token) {
	t, lit := p.nextToken()
	if t != want {
		p.panicf("expected %q but got %q (literal %q)", want, t, lit)
	}
}

func (p *parser) parseAttributes() (attr []string, err error) {
	for {
		p.skipWhitespace()
		if p.r == '(' {
			return
		}
		attr = append(attr, p.nextIdent())
		p.skipWhitespace()
		if p.r == ',' {
			p.nextRune()
		}
	}
}

func (p *parser) parseArg() (arg magentaArg, err error) {
	if p.r == ')' {
		return
	}
	arg.aname = p.nextIdent()
	p.expect(':')
	atype, err := p.parseType()
	if err != nil {
		return
	}
	arg.atype = atype
	p.skipWhitespace()
	if isLetter(p.r) {
		arg.constraint = p.nextIdent()
		p.skipWhitespace()
	}
	return
}

func (p *parser) parseSyscall() (call magentaSyscallDef, err error) {
	call.name = p.nextIdent()
	attr, err := p.parseAttributes()
	if err != nil {
		return magentaSyscallDef{}, err
	}
	for _, a := range attr {
		if a == "vdsocall" {
			call.vdsocall = true
		}
	}
	call.attr = attr
	p.expect('(')
	for {
		p.skipWhitespace()
		if p.r == ')' {
			p.nextRune()
			break
		}
		arg, err := p.parseArg()
		if err != nil {
			return magentaSyscallDef{}, err
		}
		if arg.aname == "" {
			break
		}
		call.args = append(call.args, arg)
		if p.r == ',' {
			p.nextRune()
		}
	}
	p.skipWhitespace()
	if p.r != ';' {
		kw := p.nextIdent()
		if kw != "returns" {
			p.panicf("expected \"returns\" but got \"%s\"", kw)
		}
		p.expect('(')
		rtype, err := p.parseType()
		if err != nil {
			return magentaSyscallDef{}, err
		}
		call.ret = rtype
		p.expect(')')
	}
	p.skipWhitespace()
	p.expect(';')
	return call, nil
}

func (p *parser) parseType() (t magentaType, err error) {
	ident := p.nextIdent()
	n, ok := magentaTypeNamedStr[ident]
	if !ok {
		return t, p.errorf("unknown type name: %s", ident)
	}
	t.named = n
	p.skipWhitespace()
	if p.r == '[' {
		p.nextRune()
		t.isArray = true
		t.arraySize = p.nextIdent()
		p.expect(']')
	}
	return t, nil
}

type parser struct {
	buf       []byte
	off       int
	line, col int
	name      string

	r rune
}

type token rune

const (
	tokenEOF    token = -1
	tokenBad    token = -2
	tokenIdent  token = -3
	tokenNumber token = -4
)

func (t token) String() string {
	switch t {
	case tokenEOF:
		return "token(EOF)"
	case tokenBad:
		return "token(BAD)"
	case tokenIdent:
		return "token(Ident)"
	case tokenNumber:
		return "token(Number)"
	default:
		return "token(" + string(t) + ")"
	}
}

func (p *parser) nextToken() (t token, lit string) {
	p.skipWhitespace()

	if isLetter(p.r) {
		lit = p.nextIdent()
		return tokenIdent, lit
	}
	if isNumber(p.r) {
		lit = p.nextNumber()
		return tokenNumber, lit
	}

	r := p.r
	p.nextRune()
	switch r {
	case -1:
		return tokenEOF, ""
	case '(', ')', '*', ',', ';', ':', '[', ']':
		return token(r), ""
	case '#':
		p.skipComment()
		return p.nextToken()
	}
	return tokenBad, fmt.Sprintf("%q", r)
}

func (p *parser) nextIdent() string {
	p.skipWhitespace()
	if !isLetter(p.r) && !isNumber(p.r) {
		p.panicf("expected ident but got %q", p.r)
	}
	off := p.off - 1
	for isLetter(p.r) || isNumber(p.r) {
		p.nextRune()
	}
	return string(p.buf[off : p.off-1])
}

func (p *parser) nextNumber() string {
	p.skipWhitespace()
	if !isNumber(p.r) {
		p.panicf("expected number but got %q", p.r)
	}
	off := p.off - 1
	for isNumber(p.r) {
		p.nextRune()
	}
	return string(p.buf[off : p.off-1])
}

func (p *parser) skipWhitespace() {
	for p.r == ' ' || p.r == '\t' || p.r == '\n' {
		p.nextRune()
	}
}

func (p *parser) skipComment() {
	// skip until end of line
	p.nextRune()
	for p.r != '\n' && p.r >= 0 {
		p.nextRune()
	}
}

func (p *parser) nextRune() {
	if p.off >= len(p.buf) {
		p.r = -1
		return
	}
	if p.r == '\n' {
		p.line++
		p.col = 0
	} else {
		p.col += utf8.RuneLen(p.r)
	}

	r, w := utf8.DecodeRune(p.buf[p.off:])
	if r == utf8.RuneError && w == 1 {
		p.r = -1
		p.panicf("input is not UTF-8")
		return
	}
	p.r = r
	p.off += w
}

func (p *parser) panicf(format string, args ...interface{}) {
	panic(parsePanic{err: p.errorf(format, args...)})
}

func (p *parser) errorf(format string, args ...interface{}) error {
	return fmt.Errorf("%s:%d:%d: %s", p.name, p.line, p.col, fmt.Sprintf(format, args...))
}

func isLetter(r rune) bool { return 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || r == '_' }
func isNumber(r rune) bool { return '0' <= r && r <= '9' }

type parsePanic struct {
	err error
}

func (pp parsePanic) String() string { return pp.err.Error() }

type magentaArg struct {
	aname      string
	atype      magentaType
	constraint string
}

type magentaSyscallDef struct {
	name     string
	ret      magentaType
	attr     []string
	args     []magentaArg
	vdsocall bool
}

func (call magentaSyscallDef) sysname() string {
	if call.exported() {
		return "Sys_" + call.name
	}
	return "sys_" + call.name
}

func (call magentaSyscallDef) exported() bool {
	switch call.name {
	case "handle_close",
		"handle_duplicate",
		"object_wait_one",
		"object_wait_many",
		"channel_create",
		"channel_read",
		"channel_write",
		"socket_create",
		"socket_read",
		"socket_write",
		"vmar_allocate",
		"vmar_destroy",
		"vmar_map",
		"vmar_unmap",
		"vmar_protect",
		"vmo_read",
		"vmo_write",
		"vmo_get_size",
		"vmo_set_size",
		"vmo_create",
		"vmo_op_range",
		"cprng_draw":
		return false
	default:
		return true
	}
}

