// +build ignore

// Parses syscalls.inc of Fuchsia's magenta kernel and produces Go
// assembly for calling the system calls.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"unicode/utf8"
)

var (
	stubs       = flag.Bool("stubs", false, "print only Go function stubs")
	goarch      = flag.String("goarch", "amd64", "arch to print asm for")
	fuchsiaRoot = flag.String("fuchsia_root", filepath.Join(os.Getenv("HOME"), "fuchsia"), "path to fuchsia root")
)

func main() {
	flag.Parse()
	sdkArch := ""
	switch *goarch {
	case "amd64":
		sdkArch = "x86_64"
	case "arm64":
		sdkArch = "aarch64"
	default:
		log.Fatalf("GOARCH=%s not supported", *goarch)
	}
	_ = sdkArch

	syscallsFile := filepath.Join(*fuchsiaRoot, "/magenta/system/public/magenta/syscalls.inc")
	if args := flag.Args(); len(args) != 0 {
		syscallsFile = args[0]
	}

	cpp := exec.Command(
		"cpp",
		"-DMAGENTA_SYSCALL_DEF=MAGENTA_SYSCALL_DEF",
		"-DMAGENTA_DDKCALL_DEF=MAGENTA_DDKCALL_DEF",
		syscallsFile,
	)
	b, err := cpp.CombinedOutput()
	if err != nil {
		log.Fatal("%v: %s", cpp.Args, err)
	}

	p := &parser{
		buf:  b,
		line: 1,
		name: syscallsFile,
	}
	syscalls, err := p.parse()
	if err != nil {
		log.Fatal(err)
	}

	buf := new(bytes.Buffer)
	if *stubs {
		fmt.Fprint(buf, stubsHeader)
		for _, call := range syscalls {
			fmt.Fprintf(buf, "//go:cgo_import_dynamic vdso_mx_%s mx_%s \"libmagenta.so.abi\"\n", call.name, call.name)
		}
		fmt.Fprint(buf, "\n")
		for _, call := range syscalls {
			fmt.Fprintf(buf, "//go:linkname vdso_mx_%s vdso_mx_%s\n", call.name, call.name)
		}
		fmt.Fprint(buf, "\nvar (\n")
		for _, call := range syscalls {
			fmt.Fprintf(buf, "\tvdso_mx_%s uintptr\n", call.name)
		}
		fmt.Fprint(buf, ")\n\n")
		for _, call := range syscalls {
			fmt.Fprint(buf, "//go:noescape\n")
			fmt.Fprint(buf, "//go:nosplit\n")
			printStub(buf, call)
			fmt.Fprint(buf, "\n")
		}
	} else {
		fmt.Fprint(buf, asmHeader)
		for _, call := range syscalls {
			fmt.Fprint(buf, "// ")
			printStub(buf, call)
			printAsm(buf, call)
			fmt.Fprint(buf, "\n")
		}
	}
	buf.WriteTo(os.Stdout)
}

