// +build ignore

// Parses syscalls.inc of Fuchsia's magenta kernel and produces Go
// assembly for calling the system calls.
//
// Regenerate syscall/mx with:
//
//	go run mkfuchsia.go -stubs > syscalls_fuchsia.go
//	go run mkfuchsia.go -goarch=amd64 > syscalls_fuchsia_amd64.s
//	go run mkfuchsia.go -goarch=arm64 > syscalls_fuchsia_arm64.s
//	gofmt -w *.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/ioutil"
	"log"
	"os"
	"path/filepath"
	"strings"
	"unicode/utf8"
)

var (
	stubs       = flag.Bool("stubs", false, "print only Go function stubs")
	goarch      = flag.String("goarch", "amd64", "arch to print asm for")
	fuchsiaRoot = flag.String("fuchsia_root", filepath.Join(os.Getenv("HOME"), "fuchsia"), "path to fuchsia root")
)

func main() {
	flag.Parse()
	sdkArch := ""
	switch *goarch {
	case "amd64":
		sdkArch = "x86_64"
	case "arm64":
		sdkArch = "aarch64"
	default:
		log.Fatalf("GOARCH=%s not supported", *goarch)
	}
	_ = sdkArch

	syscallsFile := filepath.Join(*fuchsiaRoot, "/magenta/system/public/magenta/syscalls.sysgen")
	if args := flag.Args(); len(args) != 0 {
		syscallsFile = args[0]
	}

	b, err := ioutil.ReadFile(syscallsFile)
	if err != nil {
		log.Fatal(err)
	}

	p := &parser{
		buf:  b,
		line: 1,
		name: syscallsFile,
	}
	syscalls, err := p.parse()
	if err != nil {
		log.Fatal(err)
	}

	buf := new(bytes.Buffer)
	if *stubs {
		fmt.Fprint(buf, stubsHeader[1:])
		for _, call := range syscalls {
			fmt.Fprintf(buf, "//go:cgo_import_dynamic vdso_mx_%s mx_%s \"libmagenta.so\"\n", call.name, call.name)
		}
		fmt.Fprint(buf, "\n")
		for _, call := range syscalls {
			fmt.Fprintf(buf, "//go:linkname vdso_mx_%s vdso_mx_%s\n", call.name, call.name)
		}
		fmt.Fprint(buf, "\nvar (\n")
		for _, call := range syscalls {
			fmt.Fprintf(buf, "\tvdso_mx_%s uintptr\n", call.name)
		}
		fmt.Fprint(buf, ")\n\n")
		for _, call := range syscalls {
			fmt.Fprint(buf, "//go:noescape\n")
			fmt.Fprint(buf, "//go:nosplit\n")
			printStub(buf, call)
			fmt.Fprint(buf, "\n")
		}
	} else {
		fmt.Fprint(buf, asmHeader[1:])
		for _, call := range syscalls {
			fmt.Fprint(buf, "// ")
			printStub(buf, call)
			printAsm(buf, call)
			fmt.Fprint(buf, "\n")
		}
	}
	buf.WriteTo(os.Stdout)
}

